def test_a_session_is_picked_from_a_target(client, fake, tmp_path, monkeypatch):
    project, _ = project_conversation(client)
    home = tmp_path / "home"
    claude = home / ".claude" / "projects" / "-home-dev-shop" / f"{SESSION_ID}.jsonl"
    codex = home / ".codex" / "sessions" / "2026" / "11" / "02" / "rollout-2026-11-02T09-00-00-0199a1b2.jsonl"
    secret = home / ".ssh" / "id_ed25519"
    for path, data in ((claude, claude_code_sample()), (codex, codex_sample()), (secret, b"private")):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    (home / ".codex" / "sessions" / "2026" / "11" / "02" / "notes.txt").write_text("not a session")
    os.utime(claude, (1_700_000_000, 1_700_000_000))
    os.utime(codex, (1_800_000_000, 1_800_000_000))
    with client.app.state.session_factory() as session:
        target = Target(environment_id=1, name="laptop", host="laptop.local", user="dev", host_key="ssh-ed25519 AAAA", folders=["/home/dev/shop"])
        session.add(target)
        session.commit()
        target_id = target.id
    monkeypatch.setattr(service, "home_files", lambda session, cipher, target: CONTAINER.files(str(home)))

    listed = client.get(f"/api/v1/environments/1/targets/{target_id}/sessions").json()
    assert [(item["tool"], item["path"], item["folder"]) for item in listed] == [
        (CODEX, "/".join(codex.relative_to(home).parts), "2026/11/02"),
        (CLAUDE_CODE, "/".join(claude.relative_to(home).parts), "-home-dev-shop"),
    ]

    body = {"target_id": target_id, "model": "claude-opus-5-5", "effort": "medium", "project_id": project["id"]}
    for path in (".ssh/id_ed25519", "../outside.jsonl", ".codex/sessions/2026/11/02/notes.txt"):
        refused = client.post("/api/v1/environments/1/conversations/import-from-target", json={**body, "path": path})
        assert refused.status_code in (409, 422), path
    imported = client.post("/api/v1/environments/1/conversations/import-from-target", json={**body, "path": listed[0]["path"]})
    assert imported.status_code == 201, imported.text
    assert imported.json()["imported"]["source"] == "target:laptop"
    assert imported.json()["imported"]["file"] == codex.name
    assert client.get("/api/v1/environments/1/targets/999/sessions").status_code == 404
    nothing_ran(client, project, fake)
