def jsonl(*lines: dict) -> bytes:
    return ("\n".join(json.dumps(line) for line in lines) + "\n").encode()


def claude_line(uuid: str, parent: str | None, kind: str, content, **extra) -> dict:
    message = {"role": kind, "content": content}
    if kind == "assistant":
        message = {"id": extra.pop("message_id"), "type": "message", "model": "claude-opus-4-1", **message}
    return {
        "parentUuid": parent,
        "isSidechain": extra.pop("sidechain", False),
        "userType": "external",
        "cwd": "/home/dev/shop",
        "sessionId": SESSION_ID,
        "version": "2.0.14",
        "gitBranch": "main",
        "type": kind,
        "message": message,
        "uuid": uuid,
        "timestamp": extra.pop("timestamp", "2026-11-01T10:00:00.000Z"),
        **extra,
    }


