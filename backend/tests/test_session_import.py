def upload(client, data: bytes, name: str, project_id: int | None):
    form = {"model": "claude-opus-5-5", "effort": "medium", "preset": "Balanced"}
    if project_id is not None:
        form["project_id"] = str(project_id)
    return client.post("/api/v1/environments/1/conversations/import", files={"file": (name, data, "application/jsonl")}, data=form)


def nothing_ran(client, project: dict, fake) -> None:
    folder = Path(client.app.state.workspace_dir) / project["folder"]
    assert not (folder / "MARKER").exists()
    assert fake.requests == []
    with client.app.state.session_factory() as session:
        for model in (AgentRunRecord, Checkpoint, UsageRecord):
            assert session.scalar(select(func.count()).select_from(model)) == 0


def test_a_claude_code_session_imports_into_the_right_blocks_and_nothing_runs(client, fake):
    project, _ = project_conversation(client)
    response = upload(client, claude_code_sample(), f"{SESSION_ID}.jsonl", project["id"])
    assert response.status_code == 201, response.text
    summary = response.json()
    assert summary["title"] == "Add a health endpoint" and summary["project_id"] == project["id"]
    imported = summary["imported"]
    assert (imported["tool"], imported["file"], imported["source"], imported["session_id"]) == (CLAUDE_CODE, f"{SESSION_ID}.jsonl", "upload", SESSION_ID)
    assert (imported["turns"], imported["tool_calls"], imported["cwd"]) == (2, 2, "/home/dev/shop")

    conversation = client.get(f"/api/v1/conversations/{summary['id']}").json()
    assert conversation["imported"]["tool"] == CLAUDE_CODE
    shape = [(message["role"], [block["type"] for block in message["content"]]) for message in conversation["messages"]]
    assert shape == [
        ("user", ["text"]),
        ("assistant", ["reasoning", "text", "tool_call", "tool_call", "text"]),
        ("user", ["text"]),
        ("assistant", ["text"]),
    ]
    first, reply, second, last = conversation["messages"]
    assert first["content"][0]["text"] == "Add a /health endpoint and run the tests."
    assert second["content"][0]["text"] == "/review app.py"
    assert last["content"][0]["text"] == "Looks good."
    bash, edit = reply["content"][2], reply["content"][3]
    assert (bash["name"], bash["input"]["command"], bash["output"], bash["is_error"], bash["imported"]) == (
        "Bash",
        "touch MARKER && pytest -q",
        "3 passed",
        False,
        True,
    )
    assert (edit["name"], edit["output"], edit["is_error"]) == ("Edit", "File does not exist.", True)
    texts = json.dumps(conversation["messages"])
    assert "abandoned" not in texts and "sub-agent" not in texts and "Caveat" not in texts
    nothing_ran(client, project, fake)
    # The imported conversation is in the sidebar's list with its marker.
    listed = client.get("/api/v1/environments/1/conversations").json()
    assert next(item for item in listed if item["id"] == summary["id"])["imported"]["tool"] == CLAUDE_CODE


